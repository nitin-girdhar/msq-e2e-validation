import { openAs, APPS } from '../../lib.mjs';
const BASE = APPS['hr-web'];
const { browser, page, log } = await openAs('org_admin');
const respPromise = page.waitForResponse((r) => /\/api\/(hr\/)?users/i.test(r.url()), { timeout: 15000 }).catch(() => null);
await page.goto(`${BASE}/leave/admin`, { waitUntil: 'networkidle', timeout: 30000 }).catch(() => {});
await page.getByRole('button', { name: /^adjustment$/i }).click().catch(() => {});
const resp = await respPromise;
console.log('users response:', resp ? resp.url() : 'none', resp ? resp.status() : '');
console.log('users body:', resp ? (await resp.text().catch(() => '')).slice(0, 500) : '');
console.log('badRequests:', log.badRequests);
await browser.close();
